/* ==========================================================
   帳票マッピング用の小さなユーティリティ
   テンプレートのマッピング定義（例: "report.date" → "B3"）は
   帳票用データモデルのドット区切りパスで項目を指定する。
   ========================================================== */

export function getFieldValue(model, path) {
  return path.split(".").reduce((acc, key) => (acc == null ? acc : acc[key]), model);
}
